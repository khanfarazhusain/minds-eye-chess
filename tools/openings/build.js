// Openings Ladder: tools/openings/l*.js (source) -> packs/opl.js (dono apps load karte hain).
// Har line course.html ke apne chess rules se replay hoti hai: illegal chaal = build fail.
// Har line ECO book (packs/openings.json) se match hoti hai; report tools/openings/report.txt mein.
// Run: node tools/openings/build.js   (engine check: node tools/openings/verify.js)
const fs=require('fs'),path=require('path'),vm=require('vm');
const ROOT=path.resolve(__dirname,'..','..');
const src=fs.readFileSync(path.join(ROOT,'course.html'),'utf8');
const a=src.indexOf("'use strict';"),z=src.indexOf('const today=');
if(a<0||z<0)throw new Error('course.html markers not found');
const fo=src.slice(src.indexOf('function fenOf('));const fenOfSrc=fo.slice(0,fo.indexOf('\n/*'));
const C=vm.runInNewContext(src.slice(a,z)+'\n'+fenOfSrc+';({parseFEN,legal,make,san,findMove,fenOf,START_FEN,mates})',{console});
const ECO=JSON.parse(fs.readFileSync(path.join(ROOT,'packs','openings.json'),'utf8'));

const SRC=fs.readdirSync(__dirname).filter(f=>/^l\d\.js$/.test(f)).sort();
const errs=[],rep=[];
function play(moves,fen,where){let p=C.parseFEN(fen||C.START_FEN);const out=[];
  for(const m of moves){const mv=C.findMove(p,m);if(!mv){errs.push(`${where}: illegal "${m}" after "${out.join(' ')}"`);return null}
    out.push(C.san(p,mv,C.legal(p)));p=C.make(p,mv)}return{p,out}}
const plyLabel=(i,m)=>(i%2===0?(i/2+1)+'.':Math.ceil(i/2)+'...')+m;
// "e4 {note} e5 ..." -> {moves, notes}
function parseLine(s){const toks=s.match(/\{[^}]*\}|[^\s{}]+/g)||[];const mv=[],notes={};
  for(const t of toks){if(t[0]==='{'){const n=t.slice(1,-1).trim();const i=mv.length-1;notes[String(i+1)]=(/^`/.test(n)?'':'`'+plyLabel(i,mv[i])+'` ')+n}else mv.push(t)}
  return{mv,notes}}
function ecoName(mv){let best=null;for(const[code,name,line]of ECO){const L=line.split(' ');
  if(L.length<=mv.length&&L.every((x,i)=>x===mv[i])&&(!best||L.length>best[2]))best=[code,name,L.length]}return best}

const out={levels:[]};
for(const f of SRC){const M=require(path.join(__dirname,f));const lv={to:M.to,road:M.road,newLevel:M.newLevel||null,lessons:[]};
  for(const L of M.lessons){const key=(M.newLevel?M.newLevel.id:M.to)+'.'+L.id;const les={id:L.id,key,title:L.title,sub:L.sub,yaad:L.yaad,steps:[]};
    L.steps.forEach((s0,k)=>{const s=Object.assign({},s0);const where=`${key} #${k} (${s.t})`;
      if(s.after!=null){const r=play(s.after.split(/\s+/).filter(Boolean),null,where);if(r){s.fen=C.fenOf(r.p);const e=ecoName(r.out);rep.push(`${where}: after ${r.out.join(' ')}  ECO: ${e?e[0]+' '+e[1]:'-'}`)}delete s.after}
      if(s.t==='line'){const{mv,notes}=parseLine(s.moves);const r=play(mv,s.fen,where);if(r){s.moves=r.out.join(' ');const e=ecoName(r.out);rep.push(`${where}: ${s.h}  ECO: ${e?e[0]+' '+e[1]+' ('+e[2]+' ply)':'NO MATCH'}  [${r.out.length} ply]`)}
        if(Object.keys(notes).length)s.notes=notes}
      if(s.t==='move'){if(!s.fen)errs.push(where+': move step without fen/after');else{const r=play(s.line,s.fen,where);
        if(r){s.line=r.out;if(s.mate&&!C.mates(r.p))errs.push(where+': mate flag but final position is not mate');if(/#$/.test(r.out[r.out.length-1])&&!C.mates(r.p))errs.push(where+': # but not mate')}
        (s.ok||[]).forEach(o=>{if(!C.findMove(C.parseFEN(s.fen),o))errs.push(where+': ok move illegal '+o)})}}
      if(s.t==='quiz'&&!(s.a>=0&&s.a<s.opts.length))errs.push(where+': bad answer index');
      les.steps.push(s)});
    lv.lessons.push(les)}
  out.levels.push(lv)}
fs.writeFileSync(path.join(__dirname,'report.txt'),rep.join('\n')+'\n');
if(errs.length){console.error(errs.join('\n'));process.exit(1)}

const js=`/* Openings Ladder (beginner se mastery). GENERATED by tools/openings/build.js: yahan edit mat karo, tools/openings/l*.js badlo.
   course.html aur road.html dono isse load karte hain. OPL.merge(COURSE) naye lessons course mein jodta hai,
   OPL.road(ROAD_LEVELS) unhe Road to 3000 ke levels mein. Saari lines course ke chess rules se check, ECO book se match. */
var OPL=(function(){var D=${JSON.stringify(out)};
function merge(C){if(!C||!C.length||C.__opl)return;C.__opl=1;D.levels.forEach(function(lv){var L;
  if(lv.newLevel){L=C.find(function(x){return x.id===lv.newLevel.id});if(!L){L=Object.assign({lessons:[]},JSON.parse(JSON.stringify(lv.newLevel)));var i=lv.newLevel.after?C.findIndex(function(x){return x.id===lv.newLevel.after}):-1;if(i<0)C.push(L);else C.splice(i+1,0,L)}}
  else L=C.find(function(x){return x.id===lv.to});if(!L)return;
  lv.lessons.forEach(function(les){if(!L.lessons.some(function(x){return x.id===les.id}))L.lessons.push(JSON.parse(JSON.stringify(les)))})})}
function road(R){if(!R||R.__opl)return;R.__opl=1;D.levels.forEach(function(lv){var L=R.find(function(x){return x.n===lv.road});if(!L)return;
  lv.lessons.forEach(function(les){if(L.lessons.indexOf(les.key)<0)L.lessons.push(les.key)})})}
return{data:D,merge:merge,road:road}})();
if(typeof module!=='undefined')module.exports=OPL;
`;
fs.writeFileSync(path.join(ROOT,'packs','opl.js'),js);
const nL=out.levels.reduce((n,l)=>n+l.lessons.length,0),nS=out.levels.reduce((n,l)=>n+l.lessons.reduce((m,x)=>m+x.steps.length,0),0);
console.log(`packs/opl.js: ${nL} lessons, ${nS} steps, ${(js.length/1024).toFixed(1)} KB`);
// course.html ka script tag cache-bust (road.html apna hash tools/road/build.js mein leta hai)
const hv=require('crypto').createHash('md5').update(js).digest('hex').slice(0,8);
const cp=path.join(ROOT,'course.html');const cs=fs.readFileSync(cp,'utf8');const cs2=cs.replace(/packs\/opl\.js\?v=[\w]+/,'packs/opl.js?v='+hv);
if(cs2!==cs){fs.writeFileSync(cp,cs2);console.log('course.html: opl.js?v='+hv)}
